#!/usr/bin/env python3
"""Build the public browser adaptations and attest source/output correspondence."""
from pathlib import Path
import argparse
import hashlib
import json
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'experiments-source/lexical'
OUTPUT = ROOT / 'experiments/lexical'
MANIFEST = ROOT / 'data/experiments-build.json'


def digest(files: list[Path], base: Path) -> str:
    result = hashlib.sha256()
    for path in sorted(files):
        result.update(path.relative_to(base).as_posix().encode() + b'\0' + path.read_bytes() + b'\0')
    return result.hexdigest()


def source_files(source: Path = SOURCE) -> list[Path]:
    files = [source / name for name in ('index.html', 'package.json', 'package-lock.json', 'vite.config.js')]
    for directory in ('src', 'public'):
        files.extend(path for path in (source / directory).rglob('*') if path.is_file())
    return files


def attestation(source: Path, output: Path) -> dict[str, str]:
    return {
        'source_sha256': digest(source_files(source), source),
        'output_sha256': digest([p for p in output.rglob('*') if p.is_file()], output),
    }


def verify_edition(root: Path, name: str, manifest: str, build_option: str = '') -> None:
    actual = attestation(root / 'experiments-source' / name, root / 'experiments' / name)
    if actual != json.loads((root / 'data' / manifest).read_text()):
        raise ValueError(f'{name} source/output differs from verified build. Run python3 execution/build_experiments.py{build_option} --install')


def verify(root: Path = ROOT) -> None:
    verify_edition(root, 'lexical', 'experiments-build.json')
    verify_edition(root, 'rack-lab', 'rack-lab-build.json', ' --rack-lab')


def refresh_default_book() -> None:
    """Embed the complete licensed book body with ten curated character, place and clue tags."""
    original = (SOURCE / 'public/texts/sherlock-holmes.txt').read_text()
    code = "import {prepareImportedText} from './src/url-intake.js';import {buildModel} from './src/model.js';process.stdin.setEncoding('utf8');let raw='';for await(const part of process.stdin)raw+=part;const text=prepareImportedText(raw,1000000).sections[0];process.stdout.write(JSON.stringify({text,words:buildModel(text).ranked.slice(0,10)}));"
    book = json.loads(subprocess.run(['node', '--input-type=module', '-e', code], input=original, text=True, capture_output=True, cwd=SOURCE, check=True, timeout=20).stdout)
    example = {'id': 'sherlock', 'title': 'Sherlock Holmes', 'description': 'The complete Adventures of Sherlock Holmes by Arthur Conan Doyle. Follow Holmes, Watson, Adler and other characters, places and clues through all twelve stories.', 'mode': 'matrix', 'focusWords': ['holmes', 'watson', 'adler', 'lestrade', 'london', 'baker', 'letter', 'photograph', 'mystery', 'murder'], 'text': book['text']}
    (SOURCE / 'src/sherlock-example.js').write_text('// Generated by execution/build_experiments.py from the licensed bundled Gutenberg source.\nexport const SHERLOCK_EXAMPLE = ' + json.dumps(example, ensure_ascii=False) + ';\n')


def bundle(source: Path, install: bool) -> None:
    if install:
        subprocess.run(['npm', 'ci', '--ignore-scripts'], cwd=source, check=True, timeout=180)
    subprocess.run(['npm', 'run', 'build'], cwd=source, check=True, timeout=180)


def write_notices(source: Path, output: Path, runtime_only: bool = False) -> None:
    # Preserve required package license notices for the bundled dependencies.
    notices = []
    modules = source / 'node_modules'
    lock = json.loads((source / 'package-lock.json').read_text())['packages'] if runtime_only else {}
    for package in sorted(modules.glob('**/package.json')):
        if any(part.startswith('.') for part in package.relative_to(modules).parts):
            continue
        if runtime_only:
            entry = lock.get(package.parent.relative_to(source).as_posix())
            if entry is None or entry.get('dev'):
                continue
        try:
            metadata = json.loads(package.read_text())
            for name in ('LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'license.md', 'LICENSE-MIT'):
                license_file = package.parent / name
                if license_file.is_file():
                    notices.append(f"{metadata.get('name')} {metadata.get('version')}\n{license_file.read_text(errors='replace')}\n")
                    break
        except (OSError, ValueError):
            continue
    (output / 'THIRD-PARTY-NOTICES.txt').write_text('\n'.join(notices))


def build(install: bool = False, rack_lab: bool = False) -> None:
    if rack_lab:
        source = ROOT / 'experiments-source/rack-lab'
        output = ROOT / 'experiments/rack-lab'
        manifest = ROOT / 'data/rack-lab-build.json'
    else:
        refresh_default_book()
        source, output, manifest = SOURCE, OUTPUT, MANIFEST
    bundle(source, install)
    write_notices(source, output, runtime_only=rack_lab)
    manifest.write_text(json.dumps(attestation(source, output), indent=2) + '\n')
    print(f'Attested source and output for the public {source.name} bundle.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--install', action='store_true')
    parser.add_argument('--verify', action='store_true')
    parser.add_argument('--rack-lab', action='store_true', help='build Rack Lab instead of Lexical')
    args = parser.parse_args()
    verify() if args.verify else build(args.install, args.rack_lab)
